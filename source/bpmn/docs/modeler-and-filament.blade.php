    <h1>Modeler & Filament Integration</h1>
    <p class="lead text-lg text-slate-600">
        <code>saccharine/bpmn</code> provides visual tooling for both authoring workflows and monitoring active tokens in real time. It operates as a standalone web interface or embeds seamlessly into <strong>Filament v5</strong> panels.
    </p>

    <hr>

    <h2>1. The Visual Modeler (<code>bpmn-js</code>)</h2>
    <p>
        The package embeds Camunda's open-source <code>bpmn-js</code> web modeler directly inside a responsive Blade view.
    </p>

    <h3>Capability-Driven UI Filtering</h3>
    <p>
        The standard BPMN 2.0 specification contains over 80 node types and markers, many of which (such as manual message choreographies or complex transaction boundaries) are unnecessary for typical queue automation.
    </p>
    <p>
        To prevent users from drafting diagrams containing nodes that the backend queue engine cannot execute, the designer uses a capability registry paired with non-destructive <code>bpmn-js</code> filter middleware. Rather than replacing core providers or hand-crafting drag-and-drop primitives, the UI derives visibility across all interactive surfaces from a single source of truth:
    </p>
    <ul>
        <li>
            <strong><code>engineCapabilities.js</code>:</strong> The central registry defining engine-supported BPMN element types (<code>DEFAULT_SUPPORTED_ELEMENTS</code>) and their corresponding action identifiers across the palette, context pad, and replace menu. Hosts can dynamically override this capability set at runtime via the fourth argument of <code>window.initBpmnDesigner(initialXml, templates, saveCallback, supportedElementsOverride)</code>.
            <ul>
                <li>Start Events &amp; End Events</li>
                <li>Service Tasks (Automated activities)</li>
                <li>User Tasks (Human approval and form nodes)</li>
                <li>Call Activities &amp; Sub-Processes</li>
                <li>Exclusive Gateways (XOR conditional splits)</li>
                <li>Parallel Gateways (AND concurrent splits and joins)</li>
            </ul>
        </li>
        <li>
            <strong><code>FilteredPaletteProvider.js</code>:</strong> Intercepts palette creation actions generated by bpmn-js and prunes entries not present in the capability registry. Canvas interaction tools (hand, lasso, space, and global connect tools) remain fully functional, and no internal provider arrays are manually modified.
        </li>
        <li>
            <strong><code>FilteredContextPadProvider.js</code>:</strong> Filters the context pad actions when clicking an existing canvas element. Unimplemented append actions are removed, while core editing tools (such as sequence flow connections, shape deletion, and the type transformation wrench) are preserved. Direct append shortcuts for engine-supported types (like Service Tasks and User Tasks) are injected where missing.
        </li>
        <li>
            <strong><code>FilteredReplaceMenuProvider.js</code>:</strong> Intercepts the "wrench" type replacement menu (<code>bpmn-replace</code>) and strips out transformation targets not supported by the queue engine. As new backend handlers are implemented, adding their BPMN type to <code>engineCapabilities.js</code> automatically surfaces them in the palette, context pad, and replace menu simultaneously.
        </li>
    </ul>

    <h2>2. Element Templates</h2>
    <p>
        Rather than requiring users to manually input raw XML properties, the modeler supports Camunda-compatible <strong>Element Templates</strong> via <code>@bpmn-io/element-template-chooser</code>.
    </p>
    <p>
        Element Templates transform the right-hand properties panel into structured form inputs tailored to your application's specific domain activities.
    </p>

    <h3>Example Template: <code>send-notification.json</code></h3>

    <pre><code class="language-json">{
  "$schema": "https://unpkg.com/@bpmn-io/element-templates@0.8.0/resources/element-template.json",
  "name": "Send Notification Activity",
  "id": "saccharine.activity.send-notification",
  "appliesTo": ["bpmn:ServiceTask"],
  "properties": [
    {
      "label": "Delivery Channel",
      "type": "Dropdown",
      "value": "mail",
      "choices": [
        {"name": "Email Mailable", "value": "mail"},
        {"name": "Slack Webhook", "value": "slack"},
        {"name": "System Audit Log", "value": "log"}
      ],
      "binding": {
        "type": "camunda:property",
        "name": "channel"
      }
    },
    {
      "label": "Recipient Template",
      "type": "String",
      "value": "@{{ customer_email }}",
      "binding": {
        "type": "camunda:inputParameter",
        "name": "recipient"
      }
    }
  ]
}</code></pre>

    <p>
        When saved, these values are written to the BPMN 2.0 XML and compiled into the <code>input_parameters</code> JSON column on the <code>workflow_nodes</code> database table.
    </p>

    <h2>3. Real-Time Telemetry & Token Cockpit</h2>
    <p>
        The package includes an interactive execution viewer built with <code>bpmn-js/lib/NavigatedViewer</code> and paired with real-time polling endpoints (<code>/tokens</code> and <code>/telemetry</code>).
    </p>

    <div>
        <img alt="Screenshot of the live telemetry canvas" src="/assets/images/saccharine-bpmn-live-telemetry.png">
    </div>

    <h3>Dynamic Token Styling</h3>
    <p>Nodes on the canvas reflect live database execution states:</p>
    <ul>
        <li><strong>Completed Nodes (<code>.bpmn-history-completed</code>):</strong> Displayed with solid blue outlines and backgrounds, indicating that the token passed through the node successfully.</li>
        <li><strong>Active Waiting Nodes (<code>.bpmn-active-token</code>):</strong> Highlighted with an emerald green border and a pulsing CSS indicator, showing that a coroutine is currently hibernated at this step.</li>
        <li><strong>Failed / Halted Nodes (<code>.bpmn-failed-token</code>):</strong> Rendered in red, showing where an unhandled exception occurred or where an administrative halt stopped the process.</li>
    </ul>

    <h3>Interactive In-Page Signals</h3>
    <p>
        Clicking an active User Task node on the canvas opens a modal displaying current <code>$userData</code> and available action buttons (such as <strong>Approve</strong>, <strong>Reject</strong>, or <strong>Request Changes</strong>). Submitting the modal immediately sends the required inbox signal to resume background queue processing.
    </p>

    <h2>4. Filament v5 Admin Integration (Stub-Based)</h2>
    <p>
        The package provides the <code>php artisan bpmn:filament</code> command, which copies ready-to-use Filament resource stubs into your application. You then register those resources in your existing Filament panel provider.
    </p>

    <h3>Scaffolding Filament Resources</h3>
    <p>Run the following Artisan command to publish resource stubs into your app:</p>

    <pre><code class="language-bash">php artisan bpmn:filament --demo</code></pre>

    <p>This publishes:</p>
    <ul>
        <li><code>app/Filament/Resources/Bpmn/WorkflowDefinitionResource.php</code> — Manage workflow keys, versions, and deployment states.</li>
        <li><code>app/Filament/Resources/Bpmn/WorkflowInstanceResource.php</code> — Inspect active, completed, suspended, and failed workflows.</li>
        <li><code>app/Filament/Resources/Bpmn/DemoOrderResource.php</code> (with <code>--demo</code>) — Interactive CRUD for testing model event triggers.</li>
    </ul>

    <p>Each resource includes its own page classes (e.g., <code>ListWorkflowDefinitions</code>) copied from the package stubs at <code>resources/stubs/filament/</code>. Use <code>--force</code> to overwrite existing stubs.</p>

    <h3>Registering in Your Filament Panel</h3>
    <p>After scaffolding, add the resources to your panel provider (<code>app/Providers/Filament/AdminPanelProvider.php</code>):</p>

    <pre><code class="language-php">use App\Filament\Resources\Bpmn\WorkflowDefinitionResource;
use App\Filament\Resources\Bpmn\WorkflowInstanceResource;

public function panel(Panel $panel): Panel
{
    return $panel
        ->default()
        ->id('admin')
        ->path('admin')
        ->resources([
            WorkflowDefinitionResource::class,
            WorkflowInstanceResource::class,
        ]);
}</code></pre>

    <h3>Included Resources</h3>
    <ul>
        <li>
            <strong><code>WorkflowDefinitionResource</code>:</strong> Manage workflow keys, versions, and deployment states. Includes a fullscreen modal canvas for updating and compiling diagrams.
        </li>
        <li>
            <strong><code>WorkflowInstanceResource</code>:</strong> Inspect active, completed, suspended, and failed workflows. Includes header actions to Suspend, Resume, or Halt running instances.
        </li>
        <li>
            <strong>Authorization:</strong> All package resources enforce standard Laravel policies defined in <code>Saccharine\Bpmn\Policies\</code>. Permission values include <code>Bpmn:View</code>, <code>Bpmn:Edit</code>, <code>Bpmn:Delete</code>, <code>Bpmn:SuspendInstance</code>, <code>Bpmn:ResumeInstance</code>, and <code>Bpmn:HaltInstance</code>.
        </li>
    </ul>

    <p class="text-sm text-slate-500 italic mt-4">
        The standalone Blade dashboard at the default address<code>/bpmn/workflows/definitions</code> remains available even without Filament. Filament integration is entirely optional and stub-based — no package-level render hooks or global asset injection are performed. The UI filtering for the modeler (Palette, Context Pad, Replace Menu) is dynamically driven by `engineCapabilities.js` to ensure only supported BPMN elements are available.
    </p>
